#!/usr/bin/env python3
"""The Bob's lessons: one file per lesson under `skills/`, an index loaded every session, and a
count of how often each lesson's tell matched a real tool call.

A lesson nobody reads again is a diary entry. Three things close the loop, and this module is the
shared part of all three:

1. **Load:** `skills/INDEX.md` is imported by the Bob's CLAUDE.md, so every session (and every
   session after a compaction) starts with one line per lesson. `--write` regenerates it from the
   files; `--check` fails when it is stale or a lesson file is malformed.
2. **Recall:** `hooks/skill_gate.py` shows a lesson's full text when a pending tool call matches one
   of its tells, and appends each match to the fire ledger.
3. **Review:** `--stats` reads that ledger. A lesson that keeps matching is a candidate to become a
   tool or a gate; one whose tell never matches has a wrong tell or no longer applies.

A lesson file starts with TOML front matter between `+++` lines:

    +++
    summary = "A capped read is a floor; print the full count before claiming absence"
    tells = [{ tool = "Bash", pattern = '\\|\\s*head\\b' }]
    +++

    # What happened, what generalises, the tell

`summary` is required and one line. `tells` is optional: `pattern` is a regex searched in the call's
input (a Bash call's command, otherwise its JSON), `tool` a regex the tool name must fully match
(default: any). `retired = "<date>: <why>"` keeps the file but drops it from the index and the gate.
"""
from __future__ import annotations

import argparse
import dataclasses
import datetime as dt
import json
import pathlib
import re
import sys
import tomllib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import bobcfg  # noqa: E402

#: Files in skills/ that are not lessons.
NOT_LESSONS = {"README.md", "INDEX.md"}
NAME = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
KEYS = {"summary", "tells", "retired"}
TELL_KEYS = {"pattern", "tool"}
SUMMARY_MAX = 160
#: Matches in the window at which a lesson is proposed for promotion to a tool or a gate.
PROMOTE_AT = 3
WINDOW_DAYS = 30
INDEX_HEAD = ("# Skills index\n\nGenerated by `skill_index.py --write` from the lesson files beside "
              "it; do not edit by hand.\nOne line per active lesson. Open the file before acting on "
              "it.\n\n")


@dataclasses.dataclass
class Tell:
    pattern: re.Pattern
    tool: re.Pattern | None

    def matches(self, tool_name: str, text: str) -> bool:
        if self.tool is not None and not self.tool.fullmatch(tool_name):
            return False
        return bool(self.pattern.search(text))


@dataclasses.dataclass
class Skill:
    name: str
    path: pathlib.Path
    summary: str
    tells: list[Tell]
    retired: str | None
    body: str

    @property
    def active(self) -> bool:
        return self.retired is None


def skills_dir() -> pathlib.Path:
    return bobcfg.bob_root() / "skills"


def fires_path() -> pathlib.Path:
    """The fire ledger: one JSON row per tool call a tell matched."""
    return bobcfg.state_home() / "skill-fires.jsonl"


def _regex(value, where: str) -> re.Pattern:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{where}: must be a non-empty string")
    try:
        return re.compile(value)
    except re.error as e:
        raise ValueError(f"{where}: not a valid regex ({e})") from None


def parse(path: pathlib.Path) -> Skill:
    """One lesson file, or ValueError naming everything wrong with it that stops the parse."""
    name = path.stem
    if not NAME.match(name):
        raise ValueError(f"{path.name}: file name must be lowercase letters, digits and hyphens")
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "+++":
        raise ValueError(f"{path.name}: must start with a +++ front-matter line")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "+++")
    except StopIteration:
        raise ValueError(f"{path.name}: front matter has no closing +++") from None
    try:
        meta = tomllib.loads("".join(lines[1:end]))
    except tomllib.TOMLDecodeError as e:
        raise ValueError(f"{path.name}: front matter is not TOML ({e})") from None
    unknown = sorted(set(meta) - KEYS)
    if unknown:
        raise ValueError(f"{path.name}: unknown key(s) {unknown}; allowed {sorted(KEYS)}")
    summary = meta.get("summary")
    if not isinstance(summary, str) or not summary.strip() or "\n" in summary.strip():
        raise ValueError(f"{path.name}: summary must be one non-empty line")
    if len(summary.strip()) > SUMMARY_MAX:
        raise ValueError(f"{path.name}: summary is {len(summary.strip())} chars, max {SUMMARY_MAX}")
    raw_tells = meta.get("tells", [])
    if not isinstance(raw_tells, list):
        raise ValueError(f"{path.name}: tells must be a list of tables")
    tells = []
    for i, t in enumerate(raw_tells):
        where = f"{path.name}: tells[{i}]"
        if not isinstance(t, dict):
            raise ValueError(f"{where}: must be a table with pattern (and optionally tool)")
        extra = sorted(set(t) - TELL_KEYS)
        if extra:
            raise ValueError(f"{where}: unknown key(s) {extra}")
        tells.append(Tell(_regex(t.get("pattern"), f"{where}.pattern"),
                          _regex(t["tool"], f"{where}.tool") if "tool" in t else None))
    retired = meta.get("retired")
    if retired is not None and (not isinstance(retired, str) or not retired.strip()):
        raise ValueError(f"{path.name}: retired must say when and why")
    return Skill(name, path, summary.strip(), tells, retired, "".join(lines[end + 1:]).strip())


def load(directory: pathlib.Path | None = None) -> tuple[list[Skill], list[str]]:
    """Every lesson that parses, sorted by name, and an error per file that does not.

    One broken file must not hide the others: the gate keeps recalling the good ones while
    `--check` reports the bad one."""
    directory = directory or skills_dir()
    if not directory.is_dir():
        return [], []
    skills, errors = [], []
    for path in sorted(directory.glob("*.md")):
        if path.name in NOT_LESSONS:
            continue
        try:
            skills.append(parse(path))
        except (ValueError, OSError) as e:
            errors.append(str(e))
    return skills, errors


def render(skills: list[Skill]) -> str:
    active = [s for s in skills if s.active]
    if not active:
        return INDEX_HEAD + "- none yet\n"
    lines = []
    for s in sorted(active, key=lambda s: s.name):
        tools = sorted({t.tool.pattern for t in s.tells if t.tool} |
                       ({"any tool"} if any(t.tool is None for t in s.tells) else set()))
        recall = f" (recalled on: {', '.join(tools)})" if s.tells else " (no tell: recalled only here)"
        lines.append(f"- [{s.name}]({s.name}.md): {s.summary}{recall}")
    return INDEX_HEAD + "\n".join(lines) + "\n"


def check(directory: pathlib.Path | None = None) -> list[str]:
    """Every reason the lessons or their index are not in order; empty when they are."""
    directory = directory or skills_dir()
    skills, errors = load(directory)
    index = directory / "INDEX.md"
    try:
        current = index.read_text(encoding="utf-8")
    except OSError:
        current = None
    if current is None:
        errors.append("INDEX.md: missing; run skill_index.py --write")
    elif current != render(skills):
        errors.append("INDEX.md: stale; run skill_index.py --write")
    return errors


def fires(path: pathlib.Path | None = None) -> list[dict]:
    """Every ledger row, malformed lines skipped: a torn append must not make the review fail."""
    path = path or fires_path()
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return []
    rows = []
    for line in text.splitlines():
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row, dict) and isinstance(row.get("skill"), str) and isinstance(row.get("at"), str):
            rows.append(row)
    return rows


def record_fire(skill: str, tool: str, session: str, injected: bool,
                path: pathlib.Path | None = None, now: dt.datetime | None = None) -> None:
    path = path or fires_path()
    row = {"at": (now or dt.datetime.now(dt.timezone.utc)).isoformat(timespec="seconds"),
           "skill": skill, "tool": tool, "session": session, "injected": injected}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(row) + "\n")


def stats(skills: list[Skill], rows: list[dict], now: dt.datetime | None = None,
          days: int = WINDOW_DAYS) -> list[dict]:
    """Per active lesson: matches and sessions in the window, the last match, and review flags.

    PROMOTE?  matched PROMOTE_AT+ times: prose is not stopping the mistake; propose a tool or gate.
    QUIET     has a tell, older than the window, never matched in it: the tell is wrong or the
              lesson no longer applies. A new lesson is not quiet; it has not had the time.
    NO TELL   nothing recalls it at the moment of use; only the index carries it.
    """
    now = now or dt.datetime.now(dt.timezone.utc)
    start = now - dt.timedelta(days=days)
    out = []
    for s in sorted((s for s in skills if s.active), key=lambda s: s.name):
        hits, last = [], None
        for r in rows:
            if r["skill"] != s.name:
                continue
            try:
                at = dt.datetime.fromisoformat(r["at"])
            except ValueError:
                continue
            if at.tzinfo is None:
                continue  # an unzoned stamp cannot be placed in the window
            last = max(last, at) if last else at
            if at >= start:
                hits.append(r)
        flags = []
        if not s.tells:
            flags.append("NO TELL")
        elif len(hits) >= PROMOTE_AT:
            flags.append("PROMOTE?")
        else:
            try:
                born = dt.datetime.fromtimestamp(s.path.stat().st_mtime, dt.timezone.utc)
            except OSError:
                born = now
            if not hits and born < start:
                flags.append("QUIET")
        out.append({"skill": s.name, "matches": len(hits),
                    "sessions": len({r.get("session") for r in hits}),
                    "last": last.isoformat(timespec="seconds") if last else None, "flags": flags})
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate skills/INDEX.md")
    mode.add_argument("--check", action="store_true",
                      help="exit 1 if a lesson file is malformed or INDEX.md is stale")
    mode.add_argument("--stats", action="store_true", help="matches per lesson and review flags")
    ap.add_argument("--days", type=int, default=WINDOW_DAYS, help="stats window (default 30)")
    a = ap.parse_args(argv)

    directory = skills_dir()
    if a.check:
        errors = check(directory)
        for e in errors:
            print(f"FAIL {e}")
        if not errors:
            print(f"OK {len(load(directory)[0])} lesson(s), index current")
        return 1 if errors else 0
    skills, errors = load(directory)
    for e in errors:
        print(f"FAIL {e}", file=sys.stderr)
    if a.write:
        directory.mkdir(parents=True, exist_ok=True)
        index = directory / "INDEX.md"
        text = render(skills)
        if index.exists() and index.read_text(encoding="utf-8") == text:
            print("INDEX.md unchanged")
        else:
            index.write_text(text, encoding="utf-8")
            print(f"INDEX.md written: {sum(s.active for s in skills)} active lesson(s)")
        return 1 if errors else 0
    if a.stats:
        rows = stats(skills, fires(), days=a.days)
        print(f"lesson matches in the last {a.days} days ({fires_path()}):")
        for r in rows:
            flags = f"  {' '.join(r['flags'])}" if r["flags"] else ""
            print(f"  {r['skill']}: {r['matches']} match(es) in {r['sessions']} session(s), "
                  f"last {r['last'] or 'never'}{flags}")
        if not rows:
            print("  no active lessons")
        return 1 if errors else 0
    sys.stdout.write(render(skills))
    return 1 if errors else 0


if __name__ == "__main__":
    import oscompat
    oscompat.utf8_stdio()
    sys.exit(main())
